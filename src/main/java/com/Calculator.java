package com;

public class Calculator {

    public float add(int i, int j) {
       
        return i + j;
    }

    public float subtract(int i, int j) {
       
        return i - j;
    }

    public float multiply(int i, int j) {
       
        return i * j;
    }

    public float divide(float i, float j) {
       
        return i / j;
    }

}
